"""Generate SLO recording rules and multi-window, multi-burn-rate alerts from slos.yaml (E9, chapter 10).

    python v2/platform/slo/gen.py     # writes v2/gitops/platform/manifests/alerts/slo-storefront.yaml

Per SLO and window w in WINDOWS: slo:error_ratio:<w>{slo=...} = errors / total over w. Alerts after the
Google SRE workbook (chapter 5, "Alerting on SLOs"), budget = 1 - objective:
  page   (critical):  ratio(1h) > 14.4 * budget and ratio(5m)  > 14.4 * budget   - 2 % of the 30-day budget in 1 h
                   or ratio(6h) >  6   * budget and ratio(30m) >  6   * budget   - 5 % in 6 h
  ticket (warning):   ratio(1d) >  3   * budget and ratio(2h)  >  3   * budget   - 10 % in 1 d
                   or ratio(3d) >  1   * budget and ratio(6h)  >  1   * budget   - 10 % in 3 d
The short window makes the alert stop soon after the burn stops. A page inhibits the ticket of the
same SLO (values/monitoring.yaml). Without traffic a ratio is NaN and nothing fires.
"""
from __future__ import annotations

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "gitops" / "platform" / "manifests" / "alerts" / "slo-storefront.yaml"
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
ALERTS = [  # (severity, slo_severity, [(long, short, burn rate)], what it means)
    ("critical", "page", [("1h", "5m", 14.4), ("6h", "30m", 6)],
     "Burn rate at least 14.4 over 1 h or 6 over 6 h: at that pace the 30-day budget is gone in about 2 or 5 days."),
    ("warning", "ticket", [("1d", "2h", 3), ("3d", "6h", 1)],
     "Burn rate at least 3 over 1 d or 1 over 3 d: at that pace the budget is gone in about 10 days or by the end of the period."),
]
RUNBOOK = "https://github.com/miku-wwl/devops-delivery/blob/v2/enterprise/v2/docs/runbooks.md#slo-burn"


def main() -> None:
    spec = yaml.safe_load((HERE / "slos.yaml").read_text(encoding="utf-8"))
    groups = []
    for s in spec["slos"]:
        name, budget = s["name"], round(1 - s["objective"] / 100, 6)
        rec = [{"record": f"slo:error_ratio:{w}",
                "expr": f"({s['errors'].replace('{{w}}', w)}) / ({s['total'].replace('{{w}}', w)})",
                "labels": {"slo": name}} for w in WINDOWS]
        alerts = []
        for sev, slo_sev, pairs, meaning in ALERTS:
            expr = "\n  or\n".join(
                f'(slo:error_ratio:{lw}{{slo="{name}"}} > {rate} * {budget} and slo:error_ratio:{sw}{{slo="{name}"}} > {rate} * {budget})'
                for lw, sw, rate in pairs)
            alerts.append({
                "alert": f"SLOBurn{''.join(p.capitalize() for p in name.split('-'))}{slo_sev.capitalize()}",
                "expr": expr,
                "labels": {"severity": sev, "slo_severity": slo_sev, "slo": name, "team": spec["team"]},
                "annotations": {
                    "summary": f"{name}: {{{{ $value | humanizePercentage }}}} of the requests failed over the long window "
                               f"(objective {s['objective']} %, error budget {budget * 100:g} %)",
                    "description": f"SLI: {s['description']}. {meaning}",
                    "runbook_url": RUNBOOK}})
        groups.append({"name": f"slo.{name}", "rules": rec + alerts})
    doc = {"apiVersion": "monitoring.coreos.com/v1", "kind": "PrometheusRule",
           "metadata": {"name": "slo-storefront", "namespace": "monitoring", "labels": {"team": spec["team"]}},
           "spec": {"groups": groups}}
    OUT.write_text("# generated by v2/platform/slo/gen.py from v2/platform/slo/slos.yaml - do not edit by hand\n"
                   + yaml.safe_dump(doc, sort_keys=False, width=200, allow_unicode=True), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(groups)} SLOs, {sum(len(g['rules']) for g in groups)} rules")


if __name__ == "__main__":
    main()
